CREATE TABLE IF NOT EXISTS public.feedback_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id integer NOT NULL,
  category varchar(16) NOT NULL,
  description varchar(2000) NOT NULL,
  source varchar(16) NOT NULL DEFAULT 'general',
  error_code varchar(64),
  reference_id varchar(80),
  page_path varchar(256),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT feedback_reports_pkey PRIMARY KEY (id),
  CONSTRAINT feedback_reports_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE,
  CONSTRAINT feedback_reports_category_supported
    CHECK (category IN ('bug', 'feedback', 'feature')),
  CONSTRAINT feedback_reports_source_supported
    CHECK (source IN ('general', 'error'))
);

CREATE INDEX IF NOT EXISTS feedback_reports_created_idx
  ON public.feedback_reports (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS feedback_reports_user_idx
  ON public.feedback_reports (user_id, created_at DESC);
